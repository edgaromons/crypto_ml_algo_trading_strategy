# Backtest Engine
# The backtest engine simulates the performance of these strategies over a
# specified period. It uses historical price data to execute trades according to
# each strategy's logic and calculates the portfolio's value over time.

def run_backtest(prices: pd.DataFrame, assets: list, market_caps: pd.DataFrame,
                 risk_free_rate: float = 0.0, nsim: int = 100,
                 lookback: int = 3):
    """Run all backtests and plot results.
    Args:
        prices: Historical prices for the selected assets.
        assets: List of asset symbols.
        market_caps: Historical market cap.
        risk_free_rate: Risk-free rate. Defaults to 0.0.
        nsim: Number of simulations for random benchmark. Defaults to 100.
        lookback: Lookback period in months for historical data. Defaults to 3.
    Returns:
        tuple: A tuple containing the backtest results for each strategy.
    """
    # Adjustments for earliest start date remain the same
    earliest_start_date = prices.index.min() + pd.DateOffset(months=3)
    filtered_prices = prices.loc[earliest_start_date:].ffill()
    # Define strategies
    hrp_strategy = bt.Strategy('Hierachical_Risk_Parity',
                              [bt.algos.RunMonthly(),
                              bt.algos.SelectAll(),
                              WeighHRP(prices, assets, lookback),
                              bt.algos.Rebalance()])
    ew_strategy = bt.Strategy('Equal_Weighted',
                             [bt.algos.RunMonthly(),
                             bt.algos.SelectAll(),
                             bt.algos.WeighEqually(),
                             bt.algos.Rebalance()])
    erc_strategy = bt.Strategy('Equal_Risk_Contribution',
                              [bt.algos.RunMonthly(),
                              bt.algos.SelectAll(),
                              WeighERC(prices, assets),
                              bt.algos.Rebalance()])
    random_strategy = bt.Strategy('Randomly_Weighted',
                                 [bt.algos.RunMonthly(),
                                 bt.algos.SelectRandomly(),
                                 bt.algos.WeighRandomly(),
                                 bt.algos.Rebalance()])
    # Create backtests
    hrp_backtest = bt.Backtest(hrp_strategy, filtered_prices[assets])
    ew_backtest = bt.Backtest(ew_strategy, filtered_prices[assets])
    erc_backtest = bt.Backtest(erc_strategy, filtered_prices[assets])
    # Run backtests
    total_result = bt.run(
        hrp_backtest,
        ew_backtest,
        erc_backtest
    )
    hrp_result = bt.run(hrp_backtest)
    ew_result = bt.run(ew_backtest)
    erc_result = bt.run(erc_backtest)
    # Run monte carlo simulation of many random portfolios
    random_benchmark_results = bt.backtest.benchmark_random(
        hrp_backtest,
        random_strategy,
        nsim
    )
    # Set the risk-free rate
    total_result.set_riskfree_rate(risk_free_rate)
    hrp_result.set_riskfree_rate(risk_free_rate)
    ew_result.set_riskfree_rate(risk_free_rate)
    erc_result.set_riskfree_rate(risk_free_rate)
    random_benchmark_results.set_riskfree_rate(risk_free_rate)
    # Plot results
    total_result.plot(figsize=(10, 6))
    plt.title('Backtest Results')
    plt.xlabel('Date')
    plt.ylabel('Portfolio Value')
    plt.legend(title='Strategy', bbox_to_anchor=(1.05, 1), loc='upper left')
    plt.grid(True)
    plt.show()
    return (
        total_result, hrp_result, ew_result, erc_result,
        random_benchmark_results
    )

