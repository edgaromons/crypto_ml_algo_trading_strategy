# Backtesting Hierarchical Risk Parity (HRP) Strategy
# The HRP strategy aims to optimize asset allocation by considering the
# hierarchical structure of asset correlations, thus potentially reducing
# portfolio volatility and improving returns.

class WeighHRP(bt.Algo):
    def __init__(self, prices, assets, lookback):
        self.prices = prices
        self.assets = assets
        self.lookback = lookback
    def __call__(self, target):
        end_date = target.now
        # Calculate start_date as lookback months before end_date
        start_date = end_date - pd.DateOffset(months=self.lookback)
        # Adjust start_date to the closest available date in prices
        available_start_dates = self.prices.index[
            self.prices.index >= start_date]
        if not available_start_dates.empty:
            adjusted_start_date = available_start_dates[0]
        else:
            print("No available start date found after the "
                  "calculated start date.")
            return False
        # Adjust end_date to the closest available date in prices
        available_end_dates = self.prices.index[
            self.prices.index <= end_date]
        if not available_end_dates.empty:
            adjusted_end_date = available_end_dates[-1]
        else:
            print("No available end date found before the calculated end date.")
            return False
        # Extract period_prices using adjusted start and end dates
        period_prices = self.prices[self.assets].loc[
            adjusted_start_date:adjusted_end_date]
        # Check if there's sufficient data within this adjusted period
        if len(period_prices) > 1:
            period_returns = returns_from_prices(period_prices)
            covariance_matrix = CovarianceShrinkage(period_prices).ledoit_wolf()
            hrp = HRPOpt(period_returns, covariance_matrix)
            hrp_portfolio = hrp.optimize(linkage_method='ward')
            target.temp['weights'] = hrp.clean_weights()
            return True
        else:
            return False

# Backtesting Equal Risk Contribution (ERC) Strategy
# The ERC strategy seeks to allocate portfolio weights in a way that each asset
# contributes equally to the portfolio's risk, aiming for a more balanced risk
# distribution across assets.

class WeighERC(bt.Algo):
    def __init__(self, prices, assets, lookback=3,
                 initial_weights=None, risk_weights=None,
                 covar_method="ledoit-wolf", risk_parity_method="ccd",
                 maximum_iterations=100, tolerance=1e-8):
        self.prices = prices
        self.assets = assets
        self.lookback = pd.DateOffset(months=lookback)
        self.initial_weights = initial_weights
        self.risk_weights = risk_weights
        self.covar_method = covar_method
        self.risk_parity_method = risk_parity_method
        self.maximum_iterations = maximum_iterations
        self.tolerance = tolerance
    def __call__(self, target):
        end_date = target.now
        # Calculate start_date as 'lookback' period before end_date
        start_date = end_date - self.lookback
        # Adjust start_date to the closest available date in prices
        available_start_dates = self.prices.index[
            self.prices.index >= start_date]
        if not available_start_dates.empty:
            adjusted_start_date = available_start_dates[0]
        else:
            print("No available start date found after the "
                  "calculated start date.")
            return False
        # Adjust end_date to the closest available date in prices
        available_end_dates = self.prices.index[
            self.prices.index <= end_date]
        if not available_end_dates.empty:
            adjusted_end_date = available_end_dates[-1]
        else:
            print("No available end date found before the "
                  "calculated end date.")
            return False
        # Extract period_prices using adjusted start and end dates
        period_prices = self.prices[self.assets].loc[
            adjusted_start_date:adjusted_end_date]
        # Ensure there's sufficient data to proceed with ERC weight calculation
        if len(period_prices) > 1:
            # Calculate returns and proceed with ERC calculation
            period_returns = period_prices.pct_change().dropna()
            try:
                tw = bt.ffn.calc_erc_weights(
                    period_returns,
                    initial_weights=self.initial_weights,
                    risk_weights=self.risk_weights,
                    covar_method=self.covar_method,
                    risk_parity_method=self.risk_parity_method,
                    maximum_iterations=self.maximum_iterations,
                    tolerance=self.tolerance,
                )
                target.temp['weights'] = tw
                return True
            except Exception as e:
                print(f"Error calculating ERC weights: {e}")
                return False
        else:
            return False

